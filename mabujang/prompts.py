def recent_text(msgs: list[dict], limit: int = 6) -> str:
    """최근 대화(관리자 요청·마부장님 보고)를 짧게 요약해 프롬프트에 넣는다."""
    who = {"owner": "관리자", "mabu": "마부장님"}
    lines = [f"[{who[m['role']]}] {m['content'][:400]}" for m in msgs if m["role"] in who][-limit:]
    return "\n".join(lines)
